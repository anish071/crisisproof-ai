const DEG = Math.PI / 180

/** Convert latitude / longitude to a point on a sphere (lon 0 faces +z). */
export function latLonToXYZ(lat: number, lon: number, r = 1): [number, number, number] {
  const p = lat * DEG
  const l = lon * DEG
  return [r * Math.cos(p) * Math.sin(l), r * Math.sin(p), r * Math.cos(p) * Math.cos(l)]
}

/** Dot-matrix land: positions and per-dot colors for a THREE.Points cloud. Browser only. */
export function buildLandPoints(radius: number, count = 26000) {
  const mask = document.createElement('canvas')
  mask.width = 720
  mask.height = 360
  const ctx = mask.getContext('2d')!
  ctx.fillStyle = '#fff'
  for (const poly of POLYS) {
    ctx.beginPath()
    poly.forEach(([lon, lat], i) => {
      const x = (lon + 180) * 2
      const y = (90 - lat) * 2
      if (i) ctx.lineTo(x, y)
      else ctx.moveTo(x, y)
    })
    ctx.closePath()
    ctx.fill()
  }
  const data = ctx.getImageData(0, 0, 720, 360).data
  const isLand = (lat: number, lon: number) => {
    const y = Math.min(359, Math.floor((90 - lat) * 2))
    const x = Math.min(719, Math.floor((lon + 180) * 2))
    return data[(y * 720 + x) * 4 + 3] > 128
  }

  const pos: number[] = []
  const col: number[] = []
  const golden = Math.PI * (3 - Math.sqrt(5))
  for (let i = 0; i < count; i++) {
    const y = 1 - (2 * (i + 0.5)) / count
    const rr = Math.sqrt(1 - y * y)
    const th = i * golden
    const x = Math.cos(th) * rr
    const z = Math.sin(th) * rr
    const lat = Math.asin(y) / DEG
    const lon = Math.atan2(x, z) / DEG
    if (!isLand(lat, lon)) continue
    pos.push(x * radius, y * radius, z * radius)
    const n = 0.5 + 0.5 * Math.sin(lat * 0.21) * Math.cos(lon * 0.17)
    if (Math.random() < 0.05) col.push(0.62, 0.4, 1)
    else col.push(0.1 + 0.15 * n, 0.82 - 0.2 * n, 0.95)
  }
  return { positions: new Float32Array(pos), colors: new Float32Array(col) }
}
